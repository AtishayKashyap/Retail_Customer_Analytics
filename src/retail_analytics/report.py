"""Write the reproducible results (quality checks and the statistical test) to reports/."""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path

import duckdb

from . import queries
from .stats import DeliveryReviewResult, analyse, format_p


def run_delivery_analysis(con: duckdb.DuckDBPyConnection, iterations: int = 2000) -> DeliveryReviewResult:
    df = queries.delivery_review(con)
    on_time = df.loc[df.delivery_group == "On time", "review_score"].to_numpy()
    late = df.loc[df.delivery_group == "Late", "review_score"].to_numpy()
    return analyse(on_time, late, iterations=iterations)


def write_reports(con: duckdb.DuckDBPyConnection, reports_dir: Path, iterations: int = 2000) -> None:
    reports_dir.mkdir(parents=True, exist_ok=True)
    result = run_delivery_analysis(con, iterations)
    (reports_dir / "delivery_review_test.json").write_text(json.dumps(result.to_dict(), indent=2) + "\n")

    checks = queries.quality_checks(con)
    checks.to_csv(reports_dir / "quality_checks.csv", index=False)

    kpi = queries.scope_kpis(con, "ALL")
    seg = queries.segment_summary(con, "ALL")
    r = result.rank_biserial
    diff = result.low_review_share_difference
    lines = [
        "# Results",
        "",
        f"Generated by `retail report` on {date.today().isoformat()} from the pinned Olist source files.",
        "",
        "## Headline KPIs (valid orders: not canceled or unavailable)",
        "",
        "| Metric | Value |",
        "|---|---:|",
        f"| Orders | {int(kpi.orders):,} |",
        f"| Customers | {int(kpi.customers):,} |",
        f"| Revenue | R$ {kpi.revenue:,.0f} |",
        f"| Average order value | R$ {kpi.avg_order_value:,.2f} |",
        f"| Average review | {kpi.avg_review_score:.2f} / 5 |",
        f"| Repeat-customer rate | {kpi.repeat_customer_rate:.1%} |",
        f"| Late-delivery rate | {kpi.late_delivery_rate:.1%} |",
        "",
        "## RFM segments",
        "",
        "| Segment | Customers | Avg orders | Revenue share | Avg recency (days) |",
        "|---|---:|---:|---:|---:|",
        *[
            f"| {s.segment} | {s.customers:,} | {s.avg_orders:.2f} | {s.revenue_share:.1%} | {s.avg_recency_days:.0f} |"
            for s in seg.itertuples()
        ],
        "",
        "## Delivery timeliness vs review score",
        "",
        "| | On time | Late |",
        "|---|---:|---:|",
        f"| Orders | {result.n_on_time:,} | {result.n_late:,} |",
        f"| Mean review | {result.mean_on_time:.2f} | {result.mean_late:.2f} |",
        f"| Median review | {result.median_on_time:.0f} | {result.median_late:.0f} |",
        f"| 1-2 star share | {result.low_review_share_on_time.estimate:.1%} "
        f"| {result.low_review_share_late.estimate:.1%} |",
        "",
        f"- Mann-Whitney U = {result.u_statistic:,.0f}, two-sided p {format_p(result.p_value)}",
        f"- Rank-biserial r = {r.estimate:.3f} (95% bootstrap CI {r.low:.3f} to {r.high:.3f})",
        f"- Late orders are {100 * diff.estimate:.1f} percentage points more likely to get 1-2 stars "
        f"(95% CI {100 * diff.low:.1f} to {100 * diff.high:.1f})",
        f"- {result.interpretation}",
        "",
        "## Data-quality checks",
        "",
        "| Group | Check | Severity | Failed rows |",
        "|---|---|---|---:|",
        *[
            f"| {c.check_group} | {c.check_name} | {c.severity} | {c.failed_rows:,} |"
            for c in checks.sort_values(["check_group", "check_name"]).itertuples()
        ],
        "",
    ]
    (reports_dir / "RESULTS.md").write_text("\n".join(lines))
